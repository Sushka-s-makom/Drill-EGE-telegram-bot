# Экзаменационные варианты — каждый по 26 заданий, назначаем номер по позиции
VARIANT_TOPIC_IDS = {111, 222, 333, 444, 555, 666, 777, 888}


def classify_by_keyword(text: str) -> tuple[int, str, float] | None:
    """Возвращает (exam_number, exam_topic, probability) или None."""
    text_lower = text.lower()
    for pattern, result in KEYWORD_RULES:
        if re.search(pattern, text_lower, re.IGNORECASE):
            return result
    return None


def is_complex_question(text: str, q_type: str) -> bool:
    """Признаки сложного/развёрнутого задания."""
    complex_markers = ["выберите все верные", "выберите верные утверждения",
                       "обоснуйте", "какие физические законы", "сделайте рисунок"]
    text_lower = text.lower()
    return q_type == "written" or any(m in text_lower for m in complex_markers)


def bump_to_complex(exam_num: int, topic: str) -> tuple[int, str]:
    """Если задание сложное, сдвигаем номер в диапазон сложных задач."""
    upgrades = {
        1: 5, 2: 6, 3: 7, 4: 8,    # механика
        9: 11, 10: 12,              # МФТ
        12: 14, 13: 16,             # электродинамика
    }
    new_num = upgrades.get(exam_num, exam_num)
    return new_num, topic


def classify_question(qid: int, text: str, q_type: str, topic_id: int,
                       variant_ranks: dict[tuple, int]) -> tuple[int, str, float]:
    """Основная функция классификации."""

    # 1. Вариант экзамена — ранг внутри варианта = номер задания
    if topic_id in VARIANT_TOPIC_IDS:
        rank = variant_ranks.get((topic_id, qid), 1)
        exam_num = max(1, min(26, rank))
        kw = classify_by_keyword(text)
        if kw:
            _, topic, prob = kw
        else:
            topic = "Общий / Все разделы"
            prob = 0.65
        return exam_num, topic, prob

    # 2. Таблица topic_id
    if topic_id in TOPIC_ID_MAP:
        exam_num, topic, prob = TOPIC_ID_MAP[topic_id]
        if is_complex_question(text, q_type):
            exam_num, topic = bump_to_complex(exam_num, topic)
            prob = max(0.55, prob - 0.10)
        return exam_num, topic, prob

    # 3. Keyword matching
    kw = classify_by_keyword(text)
    if kw:
        exam_num, topic, prob = kw
        if is_complex_question(text, q_type):
            exam_num, topic = bump_to_complex(exam_num, topic)
            prob = max(0.55, prob - 0.10)
        return exam_num, topic, prob

    # 4. Fallback
    return 21, "Общий / Все разделы", 0.40


def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    # Добавляем колонки если нет
    existing = {row[1] for row in cur.execute("PRAGMA table_info(questions)")}
    for col, typ in [("exam_number", "INTEGER"), ("exam_topic", "TEXT"), ("probability", "REAL")]:
        if col not in existing:
            cur.execute(f"ALTER TABLE questions ADD COLUMN {col} {typ}")

    # Вычисляем ранги для вариантов
    variant_ranks: dict[tuple, int] = {}
    for tid in VARIANT_TOPIC_IDS:
        rows = cur.execute(
            "SELECT id FROM questions WHERE topic_id=? ORDER BY id", (tid,)
        ).fetchall()
        for rank, (qid,) in enumerate(rows, start=1):
            variant_ranks[(tid, qid)] = rank

    # Классифицируем все задания
    questions = cur.execute(
        "SELECT id, text, type, topic_id FROM questions"
    ).fetchall()

    stats = {"total": len(questions), "from_table": 0, "from_keyword": 0, "from_variant": 0, "fallback": 0}

    for qid, text, q_type, topic_id in questions:
        if topic_id in VARIANT_TOPIC_IDS:
            stats["from_variant"] += 1
        elif topic_id in TOPIC_ID_MAP:
            stats["from_table"] += 1
        elif classify_by_keyword(text or ""):
            stats["from_keyword"] += 1
        else:
            stats["fallback"] += 1

        exam_num, topic, prob = classify_question(
            qid, text or "", q_type or "", topic_id, variant_ranks
        )
        cur.execute(
            "UPDATE questions SET exam_number=?, exam_topic=?, probability=? WHERE id=?",
            (exam_num, topic, round(prob, 2), qid)
        )

    conn.commit()
    conn.close()

    print(f"Обработано заданий: {stats['total']}")
    print(f"  По таблице topic_id:  {stats['from_table']}")
    print(f"  По вариантам:         {stats['from_variant']}")
    print(f"  По ключевым словам:   {stats['from_keyword']}")
    print(f"  Fallback (низк. ув.): {stats['fallback']}")


